import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import * as lucide from 'lucide-react';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { compileString } from 'sass';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const namesSource = readFileSync(resolve(root, 'packages/bill-ui/src/design-icon-names.ts'), 'utf8');
const names = Object.fromEntries([...namesSource.matchAll(/'([^']+)': '([^']+)'/g)].map(([, name, glyph]) => [name, glyph]));
if (Object.keys(names).length === 0)
  throw new Error('Shared design icon mapping is empty');

const categorySource = readFileSync(resolve(root, 'packages/bill-ui/src/category-icon-names.ts'), 'utf8');
const categoryNames = [...categorySource.match(/categoryGlyphNames = \[([\s\S]*?)\]/)[1].matchAll(/'([^']+)'/g)].map(([, name]) => name);
const glyphs = Object.fromEntries([...new Set([...Object.values(names), ...categoryNames])].map((glyph) => {
  if (!lucide[glyph])
    throw new Error(`Unknown Lucide glyph: ${glyph}`);
  return [glyph, renderToStaticMarkup(createElement(lucide[glyph], { size: 24, strokeWidth: 1.8 }))];
}));

const appearanceColors = {};
const chartColors = {};
for (const theme of ['glass', 'fresh', 'minimal']) {
  const css = compileString(`@use 'token-values' as t; .palette {
    @include t.appearance-default;
    @include t.semantic-default;
    ${theme !== 'glass' ? `@include t.appearance-${theme};` : ''}
    ${theme !== 'glass' ? `@include t.semantic-${theme};` : ''}
  }`, { loadPaths: [resolve(root, 'packages/bill-ui/src/styles')] }).css;
  const values = Object.fromEntries([...css.matchAll(/(--[\w-]+):([^;]+);/g)].map(([, name, value]) => [name, value.trim()]));
  chartColors[theme] = { accent: values['--ww-theme-color-mid'], inverse: '#ffffff', series: Array.from({ length: 6 }, (_, index) => values[`--ww-chart-${index + 1}`]), border: values['--ww-border-color'] };
  appearanceColors[theme] = {
    ink: values['--ww-theme-text-color'],
    muted: values['--ww-text-color-mid'],
    soft: values['--ww-text-color-soft'],
    active: values['--ww-theme-color-deep'],
    inactive: values['--ww-text-color-ghost'],
    inverse: values['--ww-primary-foreground'],
    category: values['--ww-theme-color-deep'],
    categoryActive: values['--ww-theme-color-deep'],
    expense: values['--ww-pink-color'],
    income: `rgb(${values['--ww-color-finance-income'].split(/\s+/).join(',')})`,
  };
}

function toSource(value, indent = 0) {
  if (Array.isArray(value))
    return `[${value.map(nested => toSource(nested, indent)).join(', ')}]`;
  if (typeof value === 'string')
    return `'${value.replaceAll('\\', '\\\\').replaceAll('\'', '\\\'')}'`;
  const entries = Object.entries(value).map(([name, nested]) => `${' '.repeat(indent + 2)}${name}: ${toSource(nested, indent + 2)},`);
  return `{\n${entries.join('\n')}\n${' '.repeat(indent)}}`;
}

const output = `// Generated by scripts/generate-shared-design-icons.mjs from installed Lucide and canonical Sass tokens.\n// Regenerate when glyphs or theme colors change; do not edit paths or colors here.\nexport const designIconSvg = ${toSource(glyphs)} as const;\n\nexport const designIconColors = ${toSource(appearanceColors)} as const;\n\nexport const chartPresentationColors = ${toSource(chartColors)} as const;\n`;
const outputPath = resolve(root, 'packages/bill-ui/src/design-icon-assets.ts');
const license = readFileSync(resolve(root, 'node_modules/lucide-react/LICENSE'), 'utf8');
const licensePath = resolve(root, 'packages/bill-ui/LUCIDE-LICENSE');
if (process.argv.includes('--check')) {
  if (readFileSync(outputPath, 'utf8') !== output)
    throw new Error('Shared icon assets are stale. Run pnpm sync:design-icons.');
  if (readFileSync(licensePath, 'utf8') !== license)
    throw new Error('Shared icon license is stale. Run pnpm sync:design-icons.');
}
else {
  writeFileSync(outputPath, output);
  writeFileSync(licensePath, license);
}
